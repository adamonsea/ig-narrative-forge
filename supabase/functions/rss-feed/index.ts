import { serve } from "https://deno.land/std@0.190.0/http/server.ts";
import { createClient } from "https://esm.sh/@supabase/supabase-js@2";
import { SITE_URL } from "../_shared/brandConfig.ts";
import { currentFeedSlug } from "../_shared/feedSlug.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

serve(async (req: Request) => {
  // Handle CORS preflight
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const url = new URL(req.url);
    const pathParts = url.pathname.split("/").filter(Boolean);
    const slug = pathParts[pathParts.length - 1] || url.searchParams.get("slug");

    if (!slug) {
      return new Response("Missing topic slug", { 
        status: 400, 
        headers: { ...corsHeaders, "Content-Type": "text/plain" } 
      });
    }

    console.log(`[RSS Feed] Generating feed for topic: ${slug}`);

    const supabaseUrl = Deno.env.get("SUPABASE_URL")!;
    const supabaseKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
    const supabase = createClient(supabaseUrl, supabaseKey);

    // Fetch topic with RSS enabled check
    const { data: topic, error: topicError } = await supabase
      .from("topics")
      .select("id, name, slug, description, rss_enabled, branding_config, created_by")
      .eq("slug", await currentFeedSlug(supabase, slug))
      .eq("is_active", true)
      .single();

    if (topicError || !topic) {
      console.error("[RSS Feed] Topic not found:", topicError);
      return new Response("Topic not found", { 
        status: 404, 
        headers: { ...corsHeaders, "Content-Type": "text/plain" } 
      });
    }

    // Check if RSS is enabled
    if (!topic.rss_enabled) {
      console.log(`[RSS Feed] RSS disabled for topic: ${slug}`);
      return new Response("RSS feed not available for this topic", { 
        status: 403, 
        headers: { ...corsHeaders, "Content-Type": "text/plain" } 
      });
    }
    const { data: hasPro } = await supabase.rpc('has_pro_access', { p_user_id: topic.created_by });
    if (!hasPro) return new Response('RSS feed not available for this topic', { status: 403, headers: { ...corsHeaders, 'Content-Type': 'text/plain' } });

    // Fetch last 20 published stories via topic_articles join
    const { data: stories, error: storiesError } = await supabase
      .from("stories")
      .select(`
        id,
        title,
        created_at,
        published_at,
        cover_illustration_url,
        illustration_generated_at,
        topic_articles!inner (
          topic_id,
          shared_article_content ( url )
        ),
        slides ( slide_number, content )
      `)
      .eq("topic_articles.topic_id", topic.id)
      .eq("status", "published")
      .eq("is_published", true)
      .order("published_at", { ascending: false, nullsFirst: false })
      .limit(20);

    if (storiesError) {
      console.error("[RSS Feed] Error fetching stories:", storiesError);
      return new Response("Error fetching stories", { 
        status: 500, 
        headers: { ...corsHeaders, "Content-Type": "text/plain" } 
      });
    }

    console.log(`[RSS Feed] Found ${stories?.length || 0} stories`);

    const baseUrl = SITE_URL;
    const feedUrl = `${baseUrl}/@${topic.slug}`;
    const buildDate = new Date().toUTCString();

    // Build RSS items
    const items = (stories || []).map((story) => {
      const slides = ((story.slides as any[]) || []).slice().sort((x, y) => x.slide_number - y.slide_number);
      const strip = (t: string) => (t || "").replace(/<[^>]*>/g, "").replace(/\s+/g, " ").trim();
      const title = strip(slides[0]?.content) || story.title || "Untitled story";
      const description = slides.slice(1).map((sl) => strip(sl.content)).filter(Boolean).join(" ");
      const cut = description.length > 600 ? description.slice(0, 600) : description;
      const end = cut.length < description.length ? cut.lastIndexOf(". ") : -1;
      const summary = end > 200 ? cut.slice(0, end + 1) : cut;
      const pubDate = new Date(story.published_at || story.created_at).toUTCString();
      const link = `${baseUrl}/@${topic.slug}/story/${story.id}`;
      const sourceUrl = (story.topic_articles as any)?.shared_article_content?.url || link;
      // Curatr's own pictures only: generated by Curatr (illustration_generated_at set) and stored in our
      // storage, never a publisher photo copy (".../publisher-N"). Source photos need a credit RSS can't show.
      const cover = story.cover_illustration_url as string | null;
      const image = cover && story.illustration_generated_at && cover.startsWith(`${supabaseUrl}/storage/`) && !/\/publisher-\d+\./.test(cover) ? cover : null;
      // Escape XML entities
      const escapeXml = (str: string) => str
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&apos;");

      return `
    <item>
      <title>${escapeXml(title)}</title>
      <link>${escapeXml(link)}</link>
      <description>${escapeXml(summary)}</description>
      <pubDate>${pubDate}</pubDate>
      <guid isPermaLink="true">${escapeXml(link)}</guid>
      <source url="${escapeXml(sourceUrl)}">Original source</source>${image ? `\n      <enclosure url="${escapeXml(image)}" length="0" type="${image.endsWith(".png") ? "image/png" : image.endsWith(".webp") ? "image/webp" : "image/jpeg"}"/>` : ""}
    </item>`;
    }).join("");

    const esc = (str: string) => str.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
    const rss = `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${esc(topic.name)}</title>
    <link>${feedUrl}</link>
    <description>${esc(topic.description || `Curated news from ${topic.name}`)}</description>
    <language>en-gb</language>
    <lastBuildDate>${buildDate}</lastBuildDate>
    <atom:link href="${supabaseUrl}/functions/v1/rss-feed/${topic.slug}" rel="self" type="application/rss+xml"/>
    <generator>Curatr</generator>
    <ttl>60</ttl>${items}
  </channel>
</rss>`;

    return new Response(rss, {
      headers: {
        ...corsHeaders,
        "Content-Type": "application/rss+xml; charset=utf-8",
        "Cache-Control": "public, max-age=300", // Cache for 5 minutes
      },
    });

  } catch (error) {
    console.error("[RSS Feed] Unexpected error:", error);
    return new Response(`Server error`, { 
      status: 500, 
      headers: { ...corsHeaders, "Content-Type": "text/plain" } 
    });
  }
});
